package model

import (
	"errors"
	"slices"

	"github.com/QuantumNous/new-api/common"
	"gorm.io/gorm"
)

const InvoiceNotificationOption = "InvoiceNotificationUserIDs"

const InvoiceEmailTemplatesOption = "InvoiceEmailTemplates"

type InvoiceEmailTemplate struct {
	Subject string `json:"subject"`
	HTML    string `json:"html"`
}

type InvoiceEmailTemplates struct {
	Admin    InvoiceEmailTemplate `json:"admin"`
	Customer InvoiceEmailTemplate `json:"customer"`
}

func GetInvoiceEmailTemplates() (InvoiceEmailTemplates, error) {
	var templates InvoiceEmailTemplates
	var option Option
	err := DB.Where(&Option{Key: InvoiceEmailTemplatesOption}).First(&option).Error
	if errors.Is(err, gorm.ErrRecordNotFound) {
		return templates, nil
	}
	if err != nil {
		return templates, err
	}
	if option.Value != "" {
		err = common.UnmarshalJsonStr(option.Value, &templates)
	}
	return templates, err
}

// Callers validate both templates before persisting them together.
func SaveInvoiceEmailTemplates(templates InvoiceEmailTemplates) error {
	value, err := common.Marshal(templates)
	if err != nil {
		return err
	}
	return UpdateOptionsBulk(map[string]string{InvoiceEmailTemplatesOption: string(value)})
}

type InvoiceAdministrator struct {
	Id          int    `json:"id"`
	Username    string `json:"username"`
	DisplayName string `json:"display_name"`
}

type InvoiceNotificationSettings struct {
	UserIDs        []int                  `json:"user_ids"`
	Administrators []InvoiceAdministrator `json:"administrators"`
}

func GetInvoiceNotificationSettings() (*InvoiceNotificationSettings, error) {
	settings := &InvoiceNotificationSettings{UserIDs: []int{}, Administrators: []InvoiceAdministrator{}}
	var option Option
	if err := DB.Where(&Option{Key: InvoiceNotificationOption}).First(&option).Error; err != nil && !errors.Is(err, gorm.ErrRecordNotFound) {
		return nil, err
	}
	if option.Value != "" {
		if err := common.UnmarshalJsonStr(option.Value, &settings.UserIDs); err != nil {
			return nil, err
		}
	}
	if err := DB.Model(&User{}).Select("id", "username", "display_name").Where("role >= ? AND status = ?", common.RoleAdminUser, common.UserStatusEnabled).Order("id ASC").Scan(&settings.Administrators).Error; err != nil {
		return nil, err
	}
	activeIDs := make(map[int]struct{}, len(settings.Administrators))
	for _, administrator := range settings.Administrators {
		activeIDs[administrator.Id] = struct{}{}
	}
	selected := settings.UserIDs[:0]
	for _, id := range settings.UserIDs {
		if _, active := activeIDs[id]; active {
			selected = append(selected, id)
		}
	}
	settings.UserIDs = selected
	return settings, nil
}

func SetInvoiceNotificationUsers(ids []int) error {
	if len(ids) > 100 {
		return ErrInvoiceRequestInput
	}
	ids = slices.Clone(ids)
	slices.Sort(ids)
	ids = slices.Compact(ids)
	if len(ids) > 0 {
		var count int64
		if err := DB.Model(&User{}).Where("id IN ? AND role >= ? AND status = ?", ids, common.RoleAdminUser, common.UserStatusEnabled).Count(&count).Error; err != nil {
			return err
		}
		if count != int64(len(ids)) {
			return common.NewMessage("Select active administrators for invoice notifications")
		}
	} else {
		ids = []int{}
	}
	value, err := common.Marshal(ids)
	if err != nil {
		return err
	}
	return UpdateOptionsBulk(map[string]string{InvoiceNotificationOption: string(value)})
}

// Owners may access only issued invoices. Administrators can preview pending files.
func GetInvoiceForDelivery(id, userID int, admin bool) (*InvoiceRequest, error) {
	if id <= 0 || userID <= 0 {
		return nil, gorm.ErrRecordNotFound
	}
	query := DB.Where("id = ?", id)
	if !admin {
		query = query.Where("user_id = ? AND status = ?", userID, InvoiceRequestIssued)
	}
	request := &InvoiceRequest{}
	if err := query.First(request).Error; err != nil {
		return nil, err
	}
	return request, nil
}

// reference is generated by the private storage service, never from client JSON.
func AttachInvoiceFile(id int, reference string) (*InvoiceRequest, string, error) {
	request := &InvoiceRequest{}
	var previous string
	err := DB.Transaction(func(tx *gorm.DB) error {
		if err := lockForUpdate(tx).Where("id = ? AND status IN ?", id, []string{InvoiceRequestPending, InvoiceRequestIssued}).First(request).Error; err != nil {
			return err
		}
		previous = request.InvoiceURL
		request.InvoiceURL = reference
		return tx.Model(request).Update("invoice_url", reference).Error
	})
	return request, previous, err
}
